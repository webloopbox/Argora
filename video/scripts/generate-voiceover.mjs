// Generates the AI voiceover for every narrated scene via ElevenLabs, saves
// one mp3 per scene under public/audio/, and rewrites src/data/audio-present.mjs
// so the video picks the audio up automatically.
//
//   1. cp .env.example .env  and fill ELEVENLABS_API_KEY (+ optional voice/model)
//   2. npm run voiceover
//   3. npm run studio   (or npm run render)
//
// Re-run any time you tweak narration text in src/data/script.mjs.

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { narrated } from "../src/data/script.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

// --- Minimal .env loader (no dependency) -----------------------------------
const envPath = path.join(ROOT, ".env");
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    const k = t.slice(0, eq).trim();
    const v = t.slice(eq + 1).trim().replace(/^['"]|['"]$/g, "");
    if (!(k in process.env)) process.env[k] = v;
  }
}

const API_KEY = process.env.ELEVENLABS_API_KEY;
const VOICE_ID = process.env.ELEVENLABS_VOICE_ID ?? "21m00Tcm4TlvDq8ikWAM";
const MODEL_ID = process.env.ELEVENLABS_MODEL_ID ?? "eleven_multilingual_v2";

if (!API_KEY) {
  console.error(
    "\n✖ Missing ELEVENLABS_API_KEY. Copy .env.example to .env and add your key.\n",
  );
  process.exit(1);
}

const AUDIO_DIR = path.join(ROOT, "public", "audio");
fs.mkdirSync(AUDIO_DIR, { recursive: true });

async function synth(item) {
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`;
  const res = await fetch(url, {
    method: "POST",
    headers: {
      "xi-api-key": API_KEY,
      "content-type": "application/json",
      accept: "audio/mpeg",
    },
    body: JSON.stringify({
      text: item.narration,
      model_id: MODEL_ID,
      voice_settings: {
        stability: 0.45,
        similarity_boost: 0.75,
        style: 0.15,
        use_speaker_boost: true,
      },
    }),
  });

  if (!res.ok) {
    const body = await res.text().catch(() => "");
    throw new Error(`${res.status} ${res.statusText} — ${body.slice(0, 300)}`);
  }

  const buf = Buffer.from(await res.arrayBuffer());
  const outPath = path.join(ROOT, "public", item.audio); // item.audio = "audio/xxx.mp3"
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, buf);
  return outPath;
}

function writePresence(ids) {
  const list = ids.map((id) => `  "${id}",`).join("\n");
  const content = `// @ts-check
// AUTO-GENERATED by scripts/generate-voiceover.mjs — do not edit by hand.
// Lists the scene ids that currently have a voiceover mp3 in public/audio/.

/** @type {Set<string>} */
export const present = new Set([
${list}
]);

/** @param {string} id */
export const hasAudio = (id) => present.has(id);
`;
  fs.writeFileSync(
    path.join(ROOT, "src", "data", "audio-present.mjs"),
    content,
    "utf8",
  );
}

async function main() {
  console.log(
    `\n🎙  ElevenLabs voiceover — voice ${VOICE_ID}, model ${MODEL_ID}\n`,
  );
  const done = [];
  for (const item of narrated) {
    process.stdout.write(`   ${item.id.padEnd(10)} … `);
    try {
      await synth(item);
      done.push(item.id);
      console.log("ok");
    } catch (err) {
      console.log(`FAILED (${err.message})`);
    }
    // Gentle pacing to stay clear of rate limits.
    await new Promise((r) => setTimeout(r, 350));
  }

  writePresence(done);
  console.log(
    `\n✅  ${done.length}/${narrated.length} lines generated → public/audio/`,
  );
  console.log("    src/data/audio-present.mjs updated.\n");
  if (done.length < narrated.length) process.exitCode = 1;
}

main().catch((err) => {
  console.error("\n✖ Voiceover generation failed:", err);
  process.exit(1);
});
